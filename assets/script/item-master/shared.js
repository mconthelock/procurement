export function getItemTypeMeta(type) {
	const key = String(type ?? "").trim().toUpperCase();
	return (
		ITEM_TYPE_MAP[key] || {
			label: key || "N/A",
			code: key || "-",
			badge: "badge-ghost",
		}
	);
}

export function isItemActive(status) {
	const s = String(status ?? "").trim().toUpperCase();
	return s === "IM" || s === "ACTIVE" || s === "A";
}

export function formatNumber(val, decimals = 0) {
	if (val === null || val === undefined || val === "") return "-";
	const num = Number(val);
	if (Number.isNaN(num)) return String(val);
	return num.toLocaleString("en-US", {
		minimumFractionDigits: decimals,
		maximumFractionDigits: decimals,
	});
}

export function formatCost(val, decimals = 4) {
	if (val === null || val === undefined || val === "") return "-";
	const num = Number(val);
	if (Number.isNaN(num)) return String(val);
	return num.toLocaleString("en-US", {
		minimumFractionDigits: decimals,
		maximumFractionDigits: decimals,
	});
}

export function formatBpcsDate(val) {
	if (!val || Number(val) === 0) return "-";
	const raw = String(val).trim();
	if (/^\d{8}$/.test(raw)) {
		return `${raw.slice(0, 4)}-${raw.slice(4, 6)}-${raw.slice(6, 8)}`;
	}
	if (/^\d{6}$/.test(raw)) {
		return `20${raw.slice(0, 2)}-${raw.slice(2, 4)}-${raw.slice(4, 6)}`;
	}
	return raw;
}

export function textOrDash(val) {
	if (val === null || val === undefined) return "-";
	const s = String(val).trim();
	return s === "" ? "-" : s;
}

export function normalizeFlagBadge(val) {
	const s = String(val ?? "").trim().toUpperCase();
	if (!s || s === "N" || s === "0" || s === "NO") {
		return { text: s || "NO", cls: "badge-ghost" };
	}
	if (s === "Y" || s === "1" || s === "YES" || s === "A") {
		return { text: s, cls: "badge-success" };
	}
	return { text: s, cls: "badge-info" };
}

/**
 * Normalize either a MATERIAL_STATUS_INQUIRY_VIEW row or a raw AMECMFG.IIM row
 * into a unified IIM-compatible object for rendering.
 */
export function normalizeIimRecord(raw = {}) {
	const item = raw.IPROD ?? raw.ITEM ?? "";
	const status = raw.IID ?? raw.STATUS ?? "IM";
	const desc = raw.IDESC ?? raw.PARTNAME ?? "";
	const extraDesc = raw.IDSCE ?? raw.EXTRADESC ?? "";
	const refDesc = raw.IDSCR ?? raw.REFDESC ?? "";
	const draw = raw.IDRAW ?? raw.DRAW_FORMULA ?? "";
	const itemClass = raw.ICLAS ?? raw.CLASS ?? "";
	const itemType = raw.IITYP ?? raw.TYPE ?? "";

	return {
		...raw,
		IID: status,
		IPROD: item,
		IDESC: desc,
		IDSCE: extraDesc,
		IDSCR: refDesc,
		IDRAW: draw,
		ICLAS: itemClass,
		IITYP: itemType,
		IUMS: raw.IUMS ?? raw.UMSTOCK ?? "",
		IUMP: raw.IUMP ?? raw.UMPURCH ?? "",
		IUMR: raw.IUMR ?? raw.UMSALE ?? "",
		IUMCN: raw.IUMCN ?? raw.PURCHUM_CNV ?? 0,
		IUMRC: raw.IUMRC ?? raw.SALEUM_CNV ?? 0,
		IOPB: raw.IOPB ?? raw.OPEN_BALANCE ?? 0,
		IMIN: raw.IMIN ?? raw.MINIMUM_BALANCE ?? 0,
		IRCT: raw.IRCT ?? raw.RECEIPTS_MTD ?? 0,
		IYRCT: raw.IYRCT ?? raw.RECEIPTS_YTD ?? 0,
		IISS: raw.IISS ?? raw.ISSUES_MTD ?? 0,
		IYISS: raw.IYISS ?? raw.ISSUES_YTD ?? 0,
		IADJ: raw.IADJ ?? raw.ADJUSTMENTS_MTD ?? 0,
		IYADJ: raw.IYADJ ?? raw.ADJUSTMENTS_YTD ?? 0,
		IMSLS: raw.IMSLS ?? raw.SALEUNIT_MTD ?? 0,
		IYSLS: raw.IYSLS ?? raw.SALEUNIT_YTD ?? 0,
		ILIST: raw.ILIST ?? raw.LISTPRICE ?? 0,
		ISCST: raw.ISCST ?? raw.STANDARD_COST ?? 0,
		IACST: raw.IACST ?? raw.ACTUAL_COST ?? 0,
		IDISC: raw.IDISC ?? raw.DISCOUNT_CODE ?? "",
		ILOTS: raw.ILOTS ?? raw.LOT_SIZE ?? 0,
		IBTCH: raw.IBTCH ?? raw.BATCH_SIZE ?? 0,
		IDLTR: raw.IDLTR ?? raw.DAILY_TIME_RATE ?? 0,
		ITFDY: raw.ITFDY ?? raw.FIXED_TIME_DAYS ?? 0,
		IORDP: raw.IORDP ?? raw.ORDER_POLICY_CODE ?? "",
		IMBHD: raw.IMBHD ?? raw.HORIZON_DAYS ?? 0,
		IPODY: raw.IPODY ?? raw.PERIOD_ORDER_DAYS ?? 0,
		IVEND: raw.IVEND ?? raw.VENDOR ?? 0,
		IBUYC: raw.IBUYC ?? raw.PLANNER_CODE ?? raw.BUYER_CODE ?? "",
		IPURC: raw.IPURC ?? raw.BUYER_CODE ?? "",
		IPRDA: raw.IPRDA ?? raw.MFG_ALLOC ?? 0,
		ONHAND:
			raw.ONHAND ??
			Number(raw.IOPB ?? 0) +
				Number(raw.IRCT ?? 0) -
				Number(raw.IISS ?? 0) +
				Number(raw.IADJ ?? 0),
	};
}

