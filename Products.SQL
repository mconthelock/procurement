-- ==========================================
-- 1. ตาราง CATEGORIES (โครงสร้างหมวดหมู่แบบ Tree)
-- ==========================================
CREATE TABLE CATEGORIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    PARENT_ID NUMBER,
    CONSTRAINT FK_CATEGORIES_PARENT
        FOREIGN KEY (PARENT_ID) REFERENCES CATEGORIES(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_CATEGORIES_PARENT ON CATEGORIES(PARENT_ID);


-- ==========================================
-- 2. ตาราง CATEGORY_ATTRIBUTES (ตั้งค่า Dynamic Attributes & Option Registry)
-- ==========================================
CREATE TABLE CATEGORY_ATTRIBUTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_ID NUMBER NOT NULL,
    NAME VARCHAR2(100) NOT NULL,
    DATA_TYPE VARCHAR2(20) DEFAULT 'text' NOT NULL,
    IS_REQUIRED NUMBER(1) DEFAULT 0 NOT NULL,
    OPTION_SOURCE VARCHAR2(20) DEFAULT 'none' NOT NULL,
    FIXED_OPTIONS CLOB,
    FUNCTION_NAME VARCHAR2(100),

    -- Foreign Key
    CONSTRAINT FK_CAT_ATTR_CATEGORY
        FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(ID) ON DELETE CASCADE,

    -- ป้องกันการตั้งชื่อ Attribute ซ้ำภายในหมวดหมู่เดียวกัน
    CONSTRAINT UK_CAT_ATTR_NAME UNIQUE (CATEGORY_ID, NAME),

    -- Check Constraints
    CONSTRAINT CHK_CAT_ATTR_DATA_TYPE
        CHECK (DATA_TYPE IN ('text', 'number', 'option')),
    CONSTRAINT CHK_CAT_ATTR_IS_REQ
        CHECK (IS_REQUIRED IN (0, 1)),
    CONSTRAINT CHK_CAT_ATTR_OPT_SRC
        CHECK (OPTION_SOURCE IN ('none', 'fixed', 'function')),
    CONSTRAINT CHK_FIXED_OPTIONS_JSON
        CHECK (FIXED_OPTIONS IS NULL OR FIXED_OPTIONS IS JSON)
);

CREATE INDEX IDX_CAT_ATTR_CATEGORY ON CATEGORY_ATTRIBUTES(CATEGORY_ID);


-- ==========================================
-- 3. ตาราง PRODUCTS (ข้อมูลสินค้า + Extra Attributes)
-- ==========================================
CREATE TABLE PRODUCTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SKU VARCHAR2(100) NOT NULL,
    NAME VARCHAR2(255) NOT NULL,
    DESCRIPTION CLOB,
    PRICE NUMBER(12, 2) DEFAULT 0 NOT NULL,
    COST_PRICE NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CATEGORY_ID NUMBER,
    EXTRA_ATTRIBUTES CLOB DEFAULT '{}',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT TIMESTAMP,

    -- Constraints
    CONSTRAINT UK_PRODUCTS_SKU UNIQUE (SKU),
    CONSTRAINT FK_PRODUCTS_CATEGORY
        FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(ID) ON DELETE SET NULL,
    CONSTRAINT CHK_EXTRA_ATTRS_JSON
        CHECK (EXTRA_ATTRIBUTES IS NULL OR EXTRA_ATTRIBUTES IS JSON)
);

CREATE INDEX IDX_PRODUCTS_CATEGORY ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IDX_PRODUCTS_DELETED_AT ON PRODUCTS(DELETED_AT);